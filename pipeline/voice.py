#!/usr/bin/env python3
"""Форма вброса: чем именно найденное подаётся агенту.

Ступени до этой разобраны по именам — не разметили, не записали, не нашли, не
прошло порог. Последняя молчала: факт записан, найден, вброшен в контекст и не
использован. Одна форма, зашитая в пайплайн, не сравнивается ни с чем, и
«подано плохо» на ней неотличимо от «подавать нечего».

Поэтому форм несколько. Они лежат реестром `VOICES`, называются по именам и
переключаются рубильником `XMEM_VOICE` — тем же порядком, каким переключается
схема разметки и режим памяти: окружение, файл, умолчание. Какая лучше, решает
цифра прогона, а не мнение; имя формы поэтому уходит в отчёт вместе с цифрой.

Пайплайн знает точку входа (`render`) и имя формы. Про сами формы он не знает
ничего, и новая стоит одну запись в реестре этого файла.

Числа — часть формы, а не отдельный вопрос. `plain` называет уверенность и
уместность, `directive` и `inline` не называют; где сняли, там сняли осознанно,
и довод записан в докстринге самой формы. Общее правило одно и держится во всех:
не приписывать того, чего не считали.
"""
from collections import OrderedDict

from domain import context
from infra import config


def where_of(record):
    """Обстановка куска одной строкой. Не посчитали — пустая строка."""
    return context.describe(record.get("situation")
                            if isinstance(record, dict) else None)


def plain(kept):
    """Справка блоком: сжатые утверждения, без обращений и предисловий.

    Опорная форма — та, что стояла в пайплайне зашитой, и та, с которой
    сравниваются остальные. Меняется только вместе с опорной цифрой.

    Факт уходит вместе со своей обстановкой, а не голой строкой: модель должна
    видеть, откуда факт и когда он верен, и решать сама. Строка обстановки
    разобрана по осям — сырой словарь читать тяжелее, чем не иметь вовсе.

    Числа названы оба: это справка, и агент волен ей не верить. Ни обстановку,
    ни уместность не приписываем там, где их не считали.
    """
    lines = ["Из памяти прошлых разговоров:"]
    for score, text, record in kept:
        one = " ".join(text.split())
        lines.append("- %s (уверенность %.2f)" % (one, score) if score is not None
                     else "- %s" % one)
        where, fit = where_of(record), context.fit_of(record)
        if where:
            lines.append("  обстановка: %s%s"
                         % (where, "" if fit is None else
                            " (уместность %.2f)" % fit))
    return "\n".join(lines)


def directive(kept):
    """То же содержание указанием, а не справкой.

    Справка оставляет решение агенту, и агент решает не пользоваться ею: на
    паре «город» факт доехал до контекста первой строкой и в ответ не попал.
    Указание убирает шаг «поверить ли»: сказано учитывать — учитывай.

    Числа сняты нарочно, оба. Уверенность и уместность — наш внутренний счёт,
    агент его не калибровал, и «уверенность 0.42» рядом с указанием читается
    как оговорка: указание с оговоркой исполняется хуже указания без неё.
    Обстановка остаётся: она не оценка, а условие, при котором факт верен, и
    без неё указание становится безусловным.
    """
    lines = ["Учитывай при ответе:"]
    for _score, text, record in kept:
        one = " ".join(text.split())
        where = where_of(record)
        lines.append("- %s%s" % (one, " (%s)" % where if where else ""))
    return "\n".join(lines)


def inline(kept):
    """Факт рядом с задачей, а не отдельным блоком сверху.

    Блок сверху — отдельный кусок текста, и его легко прочесть как справочный
    заголовок, к задаче не относящийся. Одной строкой факт стоит вплотную к
    вопросу, отделить его от задачи не выходит.

    Отсюда и остальное устройство: строка одна, списка нет, чисел нет — они
    сделали бы её длиннее самой задачи. Обстановка остаётся при факте в
    скобках, тем же условием, что и в указании.
    """
    said = []
    for _score, text, record in kept:
        one = " ".join(text.split())
        where = where_of(record)
        said.append("%s (%s)" % (one, where) if where else one)
    return "(про собеседника уже известно: %s. Учитывай это, отвечая ниже.)" \
        % "; ".join(said)


# Реестр форм: имя -> сборщик. Новая форма — одна запись здесь и функция рядом;
# ни пайплайн, ни прогон о ней знать не обязаны.
VOICES = OrderedDict([
    ("plain", plain),
    ("directive", directive),
    ("inline", inline),
])

# Опора сравнения и умолчание. Умолчание именно такое, потому что цифра, снятая
# до появления реестра, снята ею: смени умолчание — и вся прежняя цифра
# перестанет быть сравнимой, не изменившись ни строчкой.
DEFAULT = "plain"

# Формы, которые едут в поставке. Реестр проверки дополняют заглушками, и
# отличать одно от другого надо: сравнение форм идёт по рабочим.
SHIPPED = tuple(VOICES)


def name(asked=None):
    """Имя формы: явно названная, иначе рубильник, иначе умолчание.

    Неизвестное имя — опорная форма, а не исключение. Подсказка идёт в ходе
    человека, и упасть посреди разговора из-за опечатки в рубильнике она права
    не имеет. Прогон от этой мягкости не страдает: ключ `--voice` сверяется со
    списком форм ещё в разборе, а отчёт называет форму, которой шли.
    """
    got = (asked or config.voice() or "").strip()
    return got if got in VOICES else DEFAULT


def render(kept, voice=None):
    """Единственная точка входа: куски порога — на вход, строка — на выход.

    Пусто на входе — пусто на выходе, у любой формы: заголовок над пустым
    списком это подсказка без подсказки. Проверяется здесь, а не в каждой
    форме, чтобы правило держалось и на формах, которых ещё нет.
    """
    kept = list(kept)
    if not kept:
        return ""
    return VOICES[name(voice)](kept)
