#!/usr/bin/env bash
# Ворота как отдельный вопрос: «живая ли здесь память?» Код возврата 0 — да.
#
# Существует ради одного: чтобы ответ на этот вопрос был в проекте один. Сами
# ворота живут в common.sh на bash, потому что стоят в горячем пути до запуска
# питона. Спросить их из питона иначе значило бы переписать проверку второй
# раз — и разойтись с ней в первый же день, когда правку внесут в одну копию.
#
# Каталог берём из окружения хука, как и сами ворота: CLAUDE_PROJECT_DIR, а без
# него — текущий каталог. Проверить чужой каталог можно, назвав его первым
# аргументом.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
[ -n "$1" ] && CLAUDE_PROJECT_DIR="$1"
live
