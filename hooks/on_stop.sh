#!/usr/bin/env bash
# Точка 5: конец хода агента. Два дела подряд, оба в фоне.
#
# Первое — очередь: разбираем ТОЛЬКО её и текущий разговор, а не весь архив.
# Зовём потребителя очереди, а не сохранение напрямую: иначе очередь, которую
# наполняет хук на сообщение человека, так и остаётся непрочитанной.
#
# Второе — понимание: разговоры и события сами по себе фактами не становятся.
# Пока его звали только руками, база росла событиями и стояла фактами: сорок
# две тысячи против восьмидесяти. Идёт оно по своей отметке о прочитанном и с
# потолком на заход, поэтому конца архива тут не боимся.
#
# Сужаем понимание до архива этого проекта. Само по себе оно обходит
# ~/.claude/projects целиком — руками это осознанный поступок человека, а на
# конце хода означало бы, что разговоры всех остальных проектов уходят в
# хранилище сами, на каждом ходе и мимо ворот. Ворота пускают хук только в
# названные каталоги, и разбирать он должен ровно названное.
#
# Черта на конце пути обязательна: --only ищет подстроку, а каталоги архива это
# уплощённые пути, вложенные друг в друга. Без неё каталог проекта -dev поймал
# бы -dev-marginal-gain, -dev-job-hunt и все прочие, а домашний каталог в списке
# живых проектов — вообще весь архив.
#
# Нет транскрипта — не знаем, чей ход, и не разбираем ничей архив.
#
# Третье и четвёртое — связи и отметка исхода. Оба были написаны и оставались
# ручными командами: граф застывал на том, что посчитали руками, а поле «помогла
# ли память» не заполнялось ни разу — ради него петля и строилась.
#
# Связи считаются по всему архиву: вес карточки это число наблюдений, и проход
# по куску записал бы вес меньше правды. Полный обход на каждом ходе стоил бы
# секунд, поэтому проход сперва спрашивает свою отметку, менялся ли архив, и на
# неизменившемся выходит, не открыв ни одного файла.
#
# Отметка исхода сужена до архива этого проекта, как и понимание, и по той же
# причине: хук не должен ходить по чужим разговорам.
#
# Все в одном фоновом процессе и по очереди: понимание разбирает то, что уже
# сохранено, связи ставятся на факты, которые понимание только что записало.
# Книжка учёта у каждого своя, а замок общий — база одна, и писать
# в неё вдвоём нельзя. Ходов много: пока понимание дописывает, следующий ход
# уже запускает свою очередь, и без общего замка они встретились бы в SQLite.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
live || { cat >/dev/null; exit 0; }
PAYLOAD=$(cat)
TRANSCRIPT=$(printf '%s' "$PAYLOAD" | python3 -c \
  "import json,sys; print((json.load(sys.stdin).get('transcript_path') or ''))" 2>/dev/null)
ARGS=(--send --limit 200)
if [ -n "$TRANSCRIPT" ]; then
  ARGS+=(--transcript "$TRANSCRIPT")
  nohup bash -c 'only=$1; shift
                 python3 -m pipeline.drain "$@"
                 python3 -m pipeline.understand --send --limit 100 --only "$only"
                 python3 -m pipeline.associate --send
                 python3 -m pipeline.suggest --settle --only "$only"' \
    _ "$(dirname "$TRANSCRIPT")/" "${ARGS[@]}" >> "$STATE_DIR/save.log" 2>&1 &
else
  nohup python3 -m pipeline.drain "${ARGS[@]}" >> "$STATE_DIR/save.log" 2>&1 &
fi
exit 0
