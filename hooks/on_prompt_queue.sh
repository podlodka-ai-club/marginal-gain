#!/usr/bin/env bash
# Точка 2, первая половина: очередь. Кладёт сообщение человека на диск и всё:
# ни сети, ни думанья.
#
# Точка синхронная — ход ждёт выхода хука, — поэтому питон уходит в фон, как и
# в конце хода. Иначе застрявший запуск держит человека до самого потолка
# ожидания, а очередь никуда не спешит: её читают в конце хода.
#
# Питонья половина зовётся отсюда, а не из настроек напрямую: ворота и
# окружение живут в common.sh, и хук, минующий common.sh, минует и ворота.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
live || { cat >/dev/null; exit 0; }
PAYLOAD=$(cat)
printf '%s' "$PAYLOAD" | nohup python3 "$ROOT/hooks/on_prompt.py" \
  >>"$STATE_DIR/queue.log" 2>&1 &
exit 0
