#!/usr/bin/env python3
"""Признаки узла факта — модуль оценки.

Узел факта это все вхождения одного факта в архиве, свёрнутые по ключу.
Признак — функция от узла, возвращает число. Детерминированно: ни модели,
ни векторов, ни обучения.

Признаки считаются независимо друг от друга и ни во что не складываются.
Слой принятия решения поверх них — отдельная работа; мера записи (score_of
в domain/measure.py, ADR 0002) этим модулем не затрагивается.

Список признаков растёт по одному за шаг, каждый со своим замером на
отложенном окне. Глоссарий всех тридцати пяти и числа замера — интент
58c6a902; исследовательский стенд — research/lab/x7.
"""
import math

# Имена в порядке добавления. Стенд сверяет свои столбцы с этим списком.
NAMES = ["n_log"]


def n_log(rec):
    """Частота, сглаженная логарифмом: log(1 + число вхождений).

    Диапазон 0…∞. AUC 0.662, ДИ95 [0.549, 0.773] на 386 узлах.
    Та же величина, что repeat в score_of, но без потолка на десяти
    вхождениях: узел с тридцатью подтверждениями отличим от узла с десятью.
    """
    return math.log1p(rec["n"])


FEATURES = {"n_log": n_log}


def compute(rec):
    """Все известные признаки узла разом. {имя: число}."""
    return {name: FEATURES[name](rec) for name in NAMES}
