#!/usr/bin/env python3
"""Что такое слово вопроса. Одно правило на поиск и на отсев.

Правило жило внутри локальной базы, и это было верно ровно до тех пор, пока
слова вопроса нужны были одному лишь поиску. Отсеву ложных находок они нужны
тоже: он решает, чем именно запись зацепилась за вопрос. Разойдись два
правила — отсев считал бы попаданием не то, чем поиск нашёл запись, и оба
остались бы правы поодиночке.

Здесь же сведение слова к основе. Оно понадобилось, когда факты легли в базу на
русском: вопрос на русском их не доставал, и живой прогон встал на трёх местах
сразу.

1. Регистр. Встроенный в SQLite `lower()` знает только латиницу: `Казань` он
   оставляет как есть, и `'в Казани' LIKE '%казани%'` не совпадает ни с чем.
   Сводить регистр приходится на стороне Python, а значит — и содержимое поля,
   а не только вопрос. Сюда же `ё`: человек пишет его как придётся, и «живёт» в
   факте против «живет» в вопросе — та же несведённая буква.
2. Знак на краю слова. Точка внутри слова — буква (`db.py` это одно слово), но
   та же точка в конце предложения втягивалась в слово: вопрос «…есть дома.»
   искал `дома.` и не находил `дома`.
3. Словоформа. «завтраки» не находило «завтрак».

Отсюда и форма починки: одна функция `key` сводит текст к словам-основам, и ею
одной размечены обе стороны сравнения — и содержимое записи, и вопрос. Два
разных пути разошлись бы молча, ровно как разошлись правило поиска и правило
отсева до того, как их свели сюда.

Основу считает Snowball — тот самый русский стеммер, что стоит за поиском
почти везде. Своего списка окончаний здесь нет намеренно: он выглядит на
десяток строк, а стоит бесконечной правки под каждое слово, которое оператор
принесёт с живого прогона.

Одна оговорка про Snowball, из-за которой ключ считается ровно один раз и
только от исходного текста: повторный проход укорачивает основу дальше
(«казани» → «казан» → «каза»). Держать ключ отдельной колонкой и досчитывать
его на чтении поэтому нельзя — записанное и спрошенное разошлись бы молча.
"""
import functools
import re

import snowballstemmer

# Слово от трёх букв. Точка, слэш, двоеточие и дефис внутри слова остаются:
# `db.py`, `localhost:5008` и `job-hunt` — это по одному слову, а не по три.
WORD = re.compile(r"[\w./:-]{3,}", re.UNICODE)

# Те же знаки на краю слова буквами уже не являются: там они — пунктуация
# предложения. Обрезаем края и только края, середину слова не трогаем.
EDGE = "./:-"

# Буква, которую человек пишет как придётся. Сводим к `е` на обеих сторонах:
# «живёт» и «живет» — одно слово, а не два.
YO = str.maketrans("ёЁ", "ее")

# Ниже этого ни слово, ни основа ничего не различают. Snowball сводит «они» к
# «он», «эти» к «эт» — такой обрывок совпадает почти с любым русским текстом.
# Одно число на оба конца: разъедься они, слово проходило бы порог, а его
# основа — нет, и вопрос молча терял бы слова.
FLOOR = 3

# Русское слово: только к нему применим русский стеммер. Имя файла, ветки или
# латинское слово проходит насквозь — основа у `deploy` не наше дело.
RUSSIAN = re.compile(r"^[а-яё]+$")

_SNOWBALL = snowballstemmer.stemmer("russian")

# Служебные слова вопроса. Без отсева «какие» и «проект» тянут половину базы.
STOP = {"какие", "какой", "какая", "какое", "что", "где", "когда", "кто", "чем",
        "как", "почему", "зачем", "было", "были", "есть", "про", "для", "над",
        "файлы", "файл", "проекте", "проект", "проекта", "шла", "работа",
        "правились", "правился", "the", "what", "which", "was", "were", "did"}


@functools.lru_cache(maxsize=16384)
def stem(word):
    """Слово к основе: строчная буква, сведённая `ё` и русский Snowball.

    Не русское слово возвращается как есть: имя файла — не форма чего-то.

    Память на повторы здесь, а не у зовущего: поиск считает основу для каждой
    строки каждой таблицы, а тема, проект, ветка и имя инструмента повторяются
    в базе тысячами.
    """
    word = (word or "").lower().translate(YO)
    if not RUSSIAN.match(word):
        return word
    return _SNOWBALL.stemWord(word)


def _text(value):
    """Значение колонки текстом. Не текст — пустая строка, а не поломка.

    Разметку зовёт SQLite на всё, что лежит в поле. Колонка объявлена текстовой,
    но SQLite к типам относится свободно, и одна двоичная строка роняла бы весь
    поиск целиком вместо того, чтобы просто не совпасть.
    """
    return value if isinstance(value, str) else ""


# Слово для разметки без стеммера. Длину не ограничиваем: здесь размечают не
# вопрос к базе, а ожидание из набора, и короткое слово в нём — часть фразы
# («по одному за раз») или само ожидание («v2», «БД»). Выбрось их — и фраза
# перестанет быть фразой, а короткое ожидание не найдётся никогда.
PIECE = re.compile(r"[\w./:-]+", re.UNICODE)


def fold(text):
    """Разметка без стеммера: строчная буква, сведённая `ё`, срезанные края.

    Ею размечают обе стороны там, где сравнивают не с вопросом, а с ожиданием
    набора. Стеммер туда не годится ни с одной стороны.

    Ожидание — иногда основа («овсян», «Казан»), иногда целая фраза («задавать
    вопросы по одному за раз»). Основу стеммер укоротил бы ещё раз (он не
    идемпотентен) и увёл сравнение вширь: «каза» нашлось бы в «казак». Фразу же
    он развалил бы с другой стороны — «задавать вопросы» стало бы «задава
    вопрос», и совпасть с текстом, размеченным как угодно, ей было бы нечем.

    Основа при этом не теряется: свести регистр — значит оставить её началом
    своего слова, а сравнение идёт вхождением. «Казан» находится в «казани»
    ровно так же, как находилось бы после стеммера.
    """
    return " ".join(piece.group(0).strip(EDGE).lower().translate(YO)
                    for piece in PIECE.finditer(_text(text))
                    if piece.group(0).strip(EDGE))


def _bare(text):
    """Слова текста без краевых знаков. Общий вход у ключа и у слов вопроса."""
    for found in WORD.finditer(_text(text)):
        word = found.group(0).strip(EDGE)
        # Обрезка могла увести слово ниже порога — тогда это уже не слово.
        if len(word) >= FLOOR:
            yield word.lower().translate(YO)


def _stems(text):
    """Слова текста и их основы. Одно место, где слово становится основой.

    Обрывок короче порога выбрасывается на обеих сторонах сразу: в вопросе он
    вытащил бы половину базы, в записи — молча ждал бы такого вопроса.
    """
    for word in _bare(text):
        root = stem(word)
        if len(root) >= FLOOR:
            yield word, root


@functools.lru_cache(maxsize=8192)
def key(text):
    """Ключ поиска: слова текста, сведённые к основам, через пробел.

    Ею размечены обе стороны сравнения. Содержимое записи проходит через `key`
    в самой базе, вопрос — через `words`, и обе дороги ведут в одну и ту же
    функцию. Служебные слова здесь не отсеиваются: отсеивать их нужно в
    вопросе, а в записи они безвредны — слова вопроса их всё равно не содержат.
    """
    return " ".join(root for _word, root in _stems(text))


def words(text):
    """Слова вопроса: основы без служебных.

    Служебное узнаётся по слову, а не по его основе. Спроси мы у основы —
    вопрос терял бы слова ни за что: `stem("надо")` это «над», а «над» в списке
    стоит предлогом. Список STOP на то и собран из живых форм.
    """
    return [root for word, root in _stems(text) if word not in STOP]
