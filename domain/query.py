#!/usr/bin/env python3
"""Что такое слово вопроса. Одно правило на поиск и на отсев.

Правило жило внутри локальной базы, и это было верно ровно до тех пор, пока
слова вопроса нужны были одному лишь поиску. Отсеву ложных находок они нужны
тоже: он решает, чем именно запись зацепилась за вопрос. Разойдись два
правила — отсев считал бы попаданием не то, чем поиск нашёл запись, и оба
остались бы правы поодиночке.
"""
import re

# Слово от трёх букв. Точка, слэш, двоеточие и дефис внутри слова остаются:
# `db.py`, `localhost:5008` и `job-hunt` — это по одному слову, а не по три.
WORD = re.compile(r"[\w./:-]{3,}", re.UNICODE)

# Служебные слова вопроса. Без отсева «какие» и «проект» тянут половину базы.
STOP = {"какие", "какой", "какая", "какое", "что", "где", "когда", "кто", "чем",
        "как", "почему", "зачем", "было", "были", "есть", "про", "для", "над",
        "файлы", "файл", "проекте", "проект", "проекта", "шла", "работа",
        "правились", "правился", "the", "what", "which", "was", "were", "did"}


def words(text):
    return [w for w in (m.group(0).lower() for m in WORD.finditer(text or ""))
            if w not in STOP]
