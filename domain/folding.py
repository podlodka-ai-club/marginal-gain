#!/usr/bin/env python3
"""Правило свёртки: какие записи считаются одной и какая из них остаётся.

Память копит и умеет забывать по сроку. Чего она не умела — сворачивать: три
записи про одно и то же оставались тремя и втроём же занимали места в выдаче.
Свёртка отличается от забывания тем, что знание не теряется, а обобщается.

**Правило здесь нарочно самое узкое, какое можно проверить.** В группу сходятся
записи одного вида, охвата и проекта, у которых содержание совпадает
посимвольно — с точностью до пробелов и регистра. Никакого сравнения смыслов,
никакой близости по словам: правило слияния дублей у нас не выбрано, это
отдельный незакрытый ресёрч. Лучше свернуть мало и верно, чем много и на глаз;
широкое слияние ждёт ресёрча и приедет сюда одной функцией `norm`.

Замена берётся **из самой группы**, а не выдумывается. Причин две. Подпись
`fact_type|subject|scope` адресует факт в связях (ADR 0004), и новая подпись
означала бы узел, которого граф не знает. И она же даёт обратимость: замена
лежит там же, где лежала, а всё остальное уезжает в отставку целиком.

Остаётся тот, кто прожил бы дольше — у кого позже срок. Не самый свежий и не
самый первый: срок отодвигает обращение (ADR 0007), значит позже всех он у
того, к кому память чаще ходили. Возьми любого другого — и свёртка укорачивала
бы жизнь группе, то есть теряла бы качество ради сжатия.
"""
import re

# Оси, по которым записи обязаны совпасть, чтобы считаться одной. Тема сюда не
# входит: именно ею записи в группе и различаются. Проект — ось, а не деталь:
# одно и то же утверждение про два разных проекта это два разных факта.
AXES = ("fact_type", "scope", "project")

SPACES = re.compile(r"\s+")

# Хвостовая пунктуация и есть вся вольность правила: «правился файл базы» и
# «правился файл базы.» — одно утверждение, записанное дважды. Внутрь строки
# нормализация не лезет: там начинается смысл, а его мы здесь не трогаем.
TAIL = " .;,!…"


def norm(content):
    """Содержание в сравнимый вид. Пробелы и регистр — не разница.

    Всё прочее — разница. Расширять эту функцию значит расширять правило
    слияния, и делать это можно только с числами ресёрча на руках.
    """
    return SPACES.sub(" ", (content or "").strip()).strip(TAIL).casefold()


def bucket(row):
    """Ключ группы или None, если сворачивать не по чему.

    Пустое содержание — не тема. Сведи такие записи вместе, и свёртка склеила
    бы всё, у чего текст не разобрался, в одну случайную запись.
    """
    body = norm(row.get("content"))
    if not body:
        return None
    return tuple(row.get(name) for name in AXES) + (body,)


def groups(rows):
    """Записи, разложенные по группам. Группы короче двух не возвращаются.

    Порядок устойчивый: и группы, и записи внутри идут так же, как пришли.
    Проход по базе обязан быть повторяем — иначе два одинаковых захода
    оставили бы разные замены, и сравнить их было бы не с чем.
    """
    by_key = {}
    for row in rows:
        key = bucket(row)
        if key is None:
            continue
        by_key.setdefault(key, []).append(row)
    return [group for group in by_key.values() if len(group) > 1]


# Пустой срок значит «не протухает» (ADR 0007), и в сравнении он старше любого
# настоящего. Строкой это не выражается, поэтому подменяем его заведомо
# большей: иначе замена оказалась бы смертной, а бессмертное уехало бы в
# отставку — свёртка убила бы то, что забывание не трогает.
FOREVER = "￿"


def survivor(group):
    """Кто из группы остаётся. Тот, кто прожил бы дольше остальных.

    Ничьи разводим отметкой «когда видели», а затем подписью: две записи с
    одинаковым сроком должны давать один и тот же ответ на каждом заходе.
    """
    def life(row):
        return (row.get("valid_until") or FOREVER,
                row.get("updated_at") or "",
                "%s|%s|%s" % (row.get("fact_type") or "", row.get("subject") or "",
                              row.get("scope") or ""))

    return max(group, key=life)
