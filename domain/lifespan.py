#!/usr/bin/env python3
"""Срок жизни факта: до каких пор он считается верным.

В записи было «когда увидели» и «когда впервые», а «до каких пор верно» — нигде.
Значит вчерашняя правда и позапрошлогодняя лежали вперемешку и весили одинаково,
и отличить текущее состояние проекта от старого мусора было нечем.

Срок лежит **значением на самом факте**, а умолчание берётся из режима памяти.
Из типа факта срок не выводится: у типа своё дело — говорить, о чём запись, — а
скорость устаревания это свойство того, как памятью пользуются, и оно одно на
все факты. Один режим проще объяснить, проще замерить и нечему разъезжаться.

Формат отметки здесь один на всех и не случайно. Просроченное отбирается
сравнением строк в SQL, и разойдись формат — сравнение соврёт молча: часть
записей уедет в отложенное живой, часть останется в выдаче мёртвой. Поэтому
срок ставит одна функция, `until`, и приводит его к одному виду `stamp`.
"""
from datetime import datetime, timedelta, timezone

from infra import config
from infra.timeline import parse_time

# Режимы памяти: имя -> сколько дней факт считается верным без обращений.
# Числа взяты по порядку величины, а не измерены: неделя — рабочий спринт,
# месяц — обычная жизнь проекта, полгода — долгая. Уточнять их будет замер,
# и правится это одной строкой, потому что режим один на все факты.
MODES = {"short": 7, "normal": 30, "long": 180}

DEFAULT_MODE = "normal"

# Отметка без микросекунд и всегда в UTC. Смещение пишем буквой, а не числом:
# `+00:00` и `Z` означают один и тот же момент, но сравниваются как разные
# строки, и одного смешения хватило бы, чтобы сравнение сроков поехало.
STAMP = "%Y-%m-%dT%H:%M:%SZ"


def mode():
    """Режим памяти: окружение, файл, умолчание. Тем же порядком, что схема."""
    got = config.memory()
    return got if got in MODES else DEFAULT_MODE


def days(name=None):
    """Сколько дней живёт факт в этом режиме."""
    return MODES[name if name in MODES else mode()]


def moment(at=None):
    """Что угодно похожее на время — в datetime с часовым поясом.

    Непонятное считаем «сейчас»: срок, которого не поставили, хуже срока,
    поставленного от неточного начала. Первое означает факт, который не выбудет
    никогда, второе — сдвиг на часы.
    """
    if isinstance(at, datetime):
        got = at
    else:
        got = parse_time(at) if at else None
    if got is None:
        got = datetime.now(timezone.utc)
    return got if got.tzinfo else got.replace(tzinfo=timezone.utc)


def stamp(at=None):
    """Отметка времени в едином виде. Только отсюда, см. заголовок модуля."""
    return moment(at).astimezone(timezone.utc).strftime(STAMP)


def now():
    return stamp(None)


def until(at=None, name=None):
    """До каких пор факт верен, если считать от `at` по режиму `name`."""
    return stamp(moment(at) + timedelta(days=days(name)))


def overdue(valid_until, at=None):
    """Вышел ли срок. Пустой срок не выходит никогда: забывать не по чему."""
    if not valid_until:
        return False
    return str(valid_until) < stamp(at)
