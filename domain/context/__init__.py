#!/usr/bin/env python3
"""Обстановка: где и когда это было. Одна форма на обе стороны сравнения.

Вес отвечает «знание это или мусор», уместность — «к месту ли оно сейчас».
Второго множителя не было, и память отдавала частое вместо подходящего: факт
про правку файла в одном проекте всплывал, когда работаешь в другом.

**Форма одна.** Обстановку хода (`cwd`, ветка, время из payload хука) и
обстановку факта (поля эпизода, с которым факт связан) приводит сюда одна и та
же функция `of`. Считай их порознь — они разъедутся молча, и совпадение начнёт
считаться неверно, ничем себя не выдав. Проверяется с обеих сторон:
tests/test_relevance.py, класс TestOneShapeForBothSides.

Осей пять: проект, каталог, ветка, день недели, часть суток. Всё это уже
приходит в хук и уже лежит у эпизода — снимать обстановку не стоит ни сети, ни
обращения к модели, а хук чтения стоит в горячем пути под сроком в 10 секунд.

Признаков уместности при этом заведён двадцать один: остальные шестнадцать
лежат в `signals.py` помеченными «не сделано», вместе с тем, откуда их брать и
что мешает. Молча отсутствующий признак неотличим от забытого. Что принято, что
намеренно не делается и что не измерено — README рядом с этим файлом.

Час округляется до части суток (шесть частей по четыре часа). Иначе ось почти
никогда не совпадала бы: работа в 14:00 и в 15:00 — это одна обстановка, а не
две. Округление живёт в самой форме, а не в сравнении: сравнение тогда остаётся
поосевым равенством, и прятать в нём особые правила негде.
"""
from pathlib import Path

from domain.context import signals
from infra.timeline import when

# Оси обстановки — это сделанные признаки из реестра, а не отдельный список.
# Реестр знает все двадцать с лишним и помечает, какие сделаны: молча
# отсутствующий признак неотличим от забытого, см. signals.py и README модуля.
AXES = signals.READY

# Вес оси в уместности. Числа лежат в реестре рядом с описанием признака.
# Сумма единица, и подобраны они под порог 0.5 так, что из них читается
# правило: **проект решает, остальное уточняет**.
#
#   промах по проекту не выкупается ничем: 0.15+0.15+0.1+0.05 = 0.45 < 0.5;
#   совпадение по проекту проходит порог само: 0.55 >= 0.5.
#
# Ни одно из пяти чисел не измерено — они выведены из этого правила, а правило
# взято из наблюдения, а не из замера. См. README модуля, «Не измерено».
WEIGHTS = signals.weights()

# Часть суток: четыре часа. В форме лежит начало части, а не сам час.
HOURS_IN_PART = 4

# Уместность, когда судить нечем: общих осей у двух обстановок нет ни одной.
# Единица, а не ноль. Знание про человека — предпочтение, привычка — не
# привязано к месту, и «не совпало» читать как «не к месту» нельзя: такой факт
# выбывал бы из выдачи всюду.
NEUTRAL = 1.0

# Откуда берётся отметка времени. Порядок важен: у хода это момент хода, у
# эпизода — его начало, у факта — когда его последний раз видели.
STAMPS = ("occurred_at", "started_at", "ended_at", "updated_at")

# Охват, который обстановкой не судится вовсе. Глобальный факт — про человека,
# а не про место; приписать ему проект эпизода значило бы запереть привычку
# человека в том проекте, где её впервые заметили.
UNBOUND_SCOPE = "global"


def of(source):
    """Обстановка в общей форме: словарь по всем осям, пустое значение — None.

    Источником может быть что угодно, у чего есть поля: payload хука (`cwd`,
    `git_branch`, `occurred_at`), запись эпизода, события или разговора из
    хранилища, сам факт, уже приведённая форма. Имена полей у них разные —
    сведение имён и есть работа этой функции.

    Идемпотентна: `of(of(x)) == of(x)`. Вызывающему не надо помнить, приводил
    ли он уже.
    """
    get = (source or {}).get
    if get("scope") == UNBOUND_SCOPE:
        return {axis: None for axis in AXES}
    cwd = _clean(get("working_directory") or get("cwd"))
    hour, day = None, None
    for name in STAMPS:
        if get(name):
            hour, day = when(get(name))
            if day:
                break
    return {
        "project": _clean(get("project")) or (Path(cwd).name if cwd else None),
        "working_directory": cwd,
        "git_branch": _clean(get("git_branch")),
        "day_of_week": _clean(get("day_of_week")) or day,
        "hour_of_day": _part(get("hour_of_day") if get("hour_of_day") is not None
                             else hour),
    }


def _clean(value):
    """Пустая строка это отсутствие значения, а не значение."""
    if value is None:
        return None
    text = str(value).strip().rstrip("/")
    return text or None


def _part(hour):
    """Час в начало своей части суток. Не час — ничего."""
    try:
        return int(hour) // HOURS_IN_PART * HOURS_IN_PART
    except (TypeError, ValueError):
        return None


def fit(there, here):
    """Уместность: 0…1. Насколько обстановка факта сходится с обстановкой хода.

    Судим только по осям, которые известны с обеих сторон, и нормируем на их
    вес. Ось, которой у одной из сторон нет, не промах и не совпадение: у
    глобального факта нет проекта, и записать ему за это ноль значило бы
    выбросить всё знание про человека из любого проекта.

    Общих осей нет ни одной — судить нечем, отдаём NEUTRAL. Такой факт
    останется в выдаче или выпадет из неё по одному лишь весу, как было до
    появления уместности.

    Симметрична: у совпадения нет своей и чужой стороны.
    """
    shared = [axis for axis in AXES
              if there.get(axis) is not None and here.get(axis) is not None]
    if not shared:
        return NEUTRAL
    total = sum(WEIGHTS[axis] for axis in shared)
    hit = sum(WEIGHTS[axis] for axis in shared if there[axis] == here[axis])
    return round(hit / total, 4)


def best(situations, here):
    """Лучшая из обстановок факта. Факт встречался не один раз.

    Берём лучшую, а не среднюю: факт, однажды записанный здесь, к месту здесь —
    даже если в другой раз его видели в другом проекте. Среднее наказывало бы
    знание за то, что оно пригодилось дважды.
    """
    fits = [fit(one, here) for one in situations]
    return max(fits) if fits else NEUTRAL


def branch_of(cwd):
    """Ветка чекаута чтением `.git/HEAD`. Ни подпроцесса, ни сети.

    Хук стоит в горячем пути: запуск `git` на каждое сообщение человека стоит
    дороже всего остального снятия обстановки вместе взятого.
    """
    try:
        ref = (Path(cwd) / ".git" / "HEAD").read_text(encoding="utf-8").strip()
    except (OSError, ValueError):
        return None
    return ref.split("/", 2)[-1] if ref.startswith("ref:") else ref[:8] or None


# Как ось называется человеку и модели. Порядок — тот же, что у AXES.
LABELS = {"project": "проект", "working_directory": "каталог",
          "git_branch": "ветка", "day_of_week": "день", "hour_of_day": "часы"}


def describe(situation):
    """Обстановка одной строкой — для куска, который уходит в контекст модели.

    Модель должна видеть, откуда факт и когда он верен, и решать сама. Пустые
    оси не называем: «каталог: неизвестно» съедает потолок выдачи и ничего не
    сообщает.
    """
    parts = []
    for axis in AXES:
        value = situation.get(axis) if situation else None
        if value is None:
            continue
        if axis == "hour_of_day":
            value = "%02d–%02d" % (value, value + HOURS_IN_PART)
        parts.append("%s %s" % (LABELS[axis], value))
    return ", ".join(parts)


def fit_of(record):
    """Уместность записи, если её посчитали. Не посчитали — None, а не единица.

    Лежит здесь, а не у того, кто спрашивает: уместность приписывает записи
    `place`, а читают её порог, порядок и форма вброса. Заведи каждый своё
    чтение — и «не считали» где-нибудь превратится в единицу молча, то есть
    неуместное пройдёт порог как уместное.
    """
    return record.get("fit") if isinstance(record, dict) else None


def norm(axes):
    """Оси среза в ту же форму, что и обстановка. Неизвестная ось — ошибка.

    Молча вернуть всю базу на опечатку в имени оси нельзя: срез выглядел бы
    исправным и отвечал бы не про то, о чём спросили.
    """
    planned = [name for name in axes if name in signals.PLANNED]
    if planned:
        raise ValueError("признак заведён, но не сделан: %s, см. "
                         "domain/context/signals.py" % ", ".join(sorted(planned)))
    unknown = [name for name in axes if name not in AXES]
    if unknown:
        raise ValueError("нет такой оси обстановки: %s, есть %s"
                         % (", ".join(sorted(unknown)), ", ".join(AXES)))
    shape = of(axes)
    return {name: shape[name] for name in axes}


def matches(situation, axes):
    """Обстановка отвечает срезу, когда сходится по всем названным осям.

    По всем сразу и в одной обстановке, а не по разным: «вторник и проект X»
    это один эпизод вторника в проекте X, а не вторник где-то и X когда-то.
    """
    return all(situation.get(name) == value for name, value in axes.items())
