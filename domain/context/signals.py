BY_NAME = {signal.name: signal for signal in SIGNALS}

# Сделанные признаки, в порядке объявления. Это и есть оси формы обстановки.
READY = tuple(signal.name for signal in SIGNALS if signal.ready)

# Заведённые, но не сделанные. Отдельным именем нарочно: срез по такой оси
# должен отвечать «ось есть, но не сделана», а не «нет такой оси».
PLANNED = tuple(signal.name for signal in SIGNALS if not signal.ready)


def weights():
    """Веса сделанных признаков. Сумма обязана быть единицей."""
    return {signal.name: signal.weight for signal in SIGNALS if signal.ready}


def table():
    """Список для человека: строка на признак, сделанные и нет вперемешку.

    Вперемешку по группам, а не двумя списками: несделанное должно попадаться
    на глаза рядом со сделанным, иначе его перестают читать.
    """
    lines = []
    for group in GROUPS:
        lines.append("## %s" % group)
        for signal in SIGNALS:
            if signal.group != group:
                continue
            mark = ("вес %.2f" % signal.weight) if signal.ready else "не сделано"
            lines.append("- %s (%s) — %s. %s. Откуда: %s"
                         % (signal.name, mark, signal.label, signal.what,
                            signal.source))
    return "\n".join(lines)
