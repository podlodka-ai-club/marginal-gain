#!/usr/bin/env python3
"""Мера факта: насколько ему верить. Оценка от 0 до 1.

Три доли: повторяемость, охват проектов, свежесть. Считается по свёрнутому
узлу и ничего не знает ни про архив, ни про хранилище — только про запись
вида {"n": ..., "projects": {...}, "last": ...}.

Признаки (features) считаются рядом и в меру не входят: слой принятия решения
поверх них — отдельная работа, ADR 0002.

Доли и веса пока зашиты константами. Это известная негибкость: каждая правка
меры правит тело функции. Открывать её реестром, как признаки и извлекатель,
имеет смысл тогда, когда долей станет больше трёх.
"""
from infra import telemetry
from infra.timeline import parse_time

# Потолки: выше них добавка перестаёт расти. Повторяемость упирается в десять
# вхождений, охват — в три проекта, свежесть — в тридцать дней.
REPEAT_CAP = 10
SPREAD_CAP = 3
FRESH_DAYS = 30

# Веса долей. Сумма единица, иначе оценка выйдет за 0…1.
WEIGHTS = {"repeat": 0.5, "spread": 0.2, "fresh": 0.3}


@telemetry.traced("weigh_fact", lambda arg, out: {
    "occurrences": arg["rec"]["n"], "projects": len(arg["rec"]["projects"]),
    "score": round(out, 3)})
def score_of(rec, newest):
    """Оценка от 0 до 1. Три доли: повторяемость, охват проектов, свежесть."""
    repeat = min(rec["n"], REPEAT_CAP) / float(REPEAT_CAP)
    spread = min(len(rec["projects"]), SPREAD_CAP) / float(SPREAD_CAP)
    fresh = 0.0
    if rec["last"] and newest:
        a, b = parse_time(rec["last"]), parse_time(newest)
        if a and b:
            days = (b - a).days
            fresh = max(0.0, 1.0 - days / float(FRESH_DAYS))
    return round(WEIGHTS["repeat"] * repeat + WEIGHTS["spread"] * spread
                 + WEIGHTS["fresh"] * fresh, 3)


# ---------- обращение: что показали и чем это кончилось ----------
#
# Мера выше считает архив: сколько раз факт записан. Это частота записи, а не
# частота пользы. Лента обращений (ADR 0010) отвечает на второй вопрос — что
# показали и чем это кончилось, — и вес считается по обоим источникам.
#
# Веса меры при этом не двигаются. Подгонка коэффициентов исчерпана дважды и на
# двух классах функций (research-4, research-7); здесь добавляется источник
# сигнала, а не перебираются старые числа.

# Потолки обращения. Показ упирается в десять вбросов, польза и отказ — в три
# ответа: три «помог» подряд говорят про запись всё, что скажут десять.
SHOWN_CAP = 10
HELPED_CAP = 3
HARM_CAP = 3

# Веса счётчиков. Показ и польза считаются порознь, и показ весит вшестеро
# меньше. Это не подгонка, а условие несамонакрутки: подсказка сама решает, что
# показать, и показ наравне с пользой поднимал бы вес тому, что она же и
# выбрала. Отказ отрицательный: «показали и не помогло» — это довод против
# записи, а не отсутствие довода за.
USE_WEIGHTS = {"shown": 0.1, "helped": 0.6, "harm": -0.3}

# Насколько лента способна сдвинуть меру архива. Половина: лента моложе архива,
# на ней два десятка вставок, и отдавать ей целое число рано.
USE_SHARE = 0.5

# Пол прямого указания. Указание — утверждение, а не гипотеза: порог оно
# проходит с первого раза, не дожидаясь повторов. Именно пол, а не готовое
# значение: повтор и польза поднимают выше, а отказы ниже не опускают.
TOLD_FLOOR = 0.9


def use_of(got):
    """Надбавка от ленты обращений по одной записи. Пустая история — ровно ноль.

    `got` — счётчики `domain.ledger.tally` по этой записи: сколько раз показана,
    сколько раз помогла, сколько раз не помогла. Молчание агента (`unknown`) не
    считается ни за, ни против: свали его в отказ — и вес поедет вниз на всех
    записях сразу, а мерили бы мы отзывчивость агента, а не пользу.

    Ноль на пустой ленте — не мелочь оформления. Факт без единого обращения
    обнуляться не должен: обращений нет у всего, что записано вчера.
    """
    if not got:
        return 0.0
    shown = min(got.get("shown", 0), SHOWN_CAP) / float(SHOWN_CAP)
    helped = min(got.get("helped", 0), HELPED_CAP) / float(HELPED_CAP)
    harm = min(got.get("not_helped", 0), HARM_CAP) / float(HARM_CAP)
    return (USE_WEIGHTS["shown"] * shown + USE_WEIGHTS["helped"] * helped
            + USE_WEIGHTS["harm"] * harm)


@telemetry.traced("weigh_use", lambda arg, out: {
    "occurrences": arg["rec"]["n"], "told": int(bool(arg["rec"].get("told"))),
    "shown": (arg["rec"].get("use") or {}).get("shown", 0),
    "helped": (arg["rec"].get("use") or {}).get("helped", 0),
    "weight": round(out, 3)})
def weight_of(rec, newest):
    """Вес факта: мера архива плюс сдвиг от ленты. От 0 до 1.

    Счётчики ленты и признак прямого указания лежат на самом узле (`use`,
    `told`), а не приходят отдельным доводом: узел собирается один раз в
    `understand.weigh`, и там же сходятся два ключевых пространства — ключ
    архива и ключ записи, которым лента считает показы.

    Прямое указание ставит пол, а не значение. Ниже пола оно не опускается даже
    после отказов: отказ снял агент, а сказал факт человек.
    """
    score = score_of(rec, newest) + USE_SHARE * use_of(rec.get("use"))
    if rec.get("told"):
        score = max(score, TOLD_FLOOR)
    return round(min(1.0, max(0.0, score)), 3)
