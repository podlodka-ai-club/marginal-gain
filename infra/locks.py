#!/usr/bin/env python3
"""Замок на один проход. Ниже всех слоёв: его держат и очередь, и понимание.

Оба прохода по архиву ведут свою книжку учёта: читают её целиком и целиком
перезаписывают. Два прохода разом — и проигравший откатывает продвижение
победителя. Раз правило общее, замок общий тоже, а не переписан дважды.
"""
import contextlib
import fcntl

from infra import config

# Один замок на оба прохода, а не по замку на проход. Дело не только в книжке
# учёта: очередь и понимание пишут в одну базу, а SQLite открыт без журнала
# упреждающей записи. Замки врозь означали бы двух писателей разом — хук конца
# хода зовёт проходы подряд, но ходов много, и пока понимание дописывает, ход
# следующий уже запускает свою очередь.
#
# Имя историческое: замок завёлся у сохранения и переименовывать его незачем.
PASS = config.state_dir() / "save.lock"


@contextlib.contextmanager
def alone(path):
    """Один проход за раз. Отдаёт True, если замок достался.

    Замок неблокирующий, и это важно. Прежний хук конца хода проверял занятость
    сам, через `flock -n`, и просто не запускался. Когда проверка переехала в
    питон с блокирующим LOCK_EX, пережившая ход запись стала собирать за собой
    очередь фоновых процессов: каждый конец хода порождал ещё один, все ждали,
    а дождавшись — по очереди разбирали один и тот же транскрипт.

    Занято значит «уже разбирают». Ждать нечего: тот, кто держит замок,
    разберёт и то, что мы собирались.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except (BlockingIOError, OSError):
            yield False
            return
        try:
            yield True
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)
