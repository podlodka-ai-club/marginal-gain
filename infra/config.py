#!/usr/bin/env python3
"""Настройка снаружи кода: одно имя, по которому выбирается схема разметки.

Порядок силы тот же, что у хуков: окружение сильнее файла, файл сильнее
умолчания. Правка кода не нужна ни для одной половины сравнения — так же, как
не нужна для переключения пути наружу (`XMEM_BACKEND`, см. `hooks/common.sh`).

Здесь нет ни текста просьбы, ни знания о внешнем формате: и то и другое живёт
в схеме, парой. Настройка называет схему, а не описывает её — иначе просьба и
маппер разъезжаются, и первым же следствием будет блок, который никто не умеет
разобрать.
"""
import os
from pathlib import Path

STATE_DIR = Path.home() / ".local" / "state" / "memory-encoder"

# Схема разметки по умолчанию. Имя должно быть в реестре domain/marks.py.
DEFAULT_MARKS = "xmd1"

# Режим памяти по умолчанию. Имя должно быть в реестре domain/lifespan.py.
# Здесь только имя: сколько это дней, знает режим, а не настройка.
DEFAULT_MEMORY = "normal"

# Слова, означающие «нет». Одни и те же в питоне и в bash: рубильник ставят и
# командой, и рукой в окружении, и понимать он должен обе привычки.
SHOW = ("0", "no", "off", "show", "false")


def setting(env, file_name, default):
    """Значение настройки: окружение, потом файл, потом умолчание.

    Файл читаем целиком по первой строке и без пробелов: писать его будут
    руками через `echo`, и хвостовой перевод строки не должен делать имя
    схемы неизвестным.
    """
    got = (os.environ.get(env) or "").strip()
    if got:
        return got
    target = STATE_DIR / file_name
    try:
        got = target.read_text(encoding="utf-8").splitlines()[0].strip()
    except (OSError, IndexError):
        got = ""
    return got or default


def marks():
    """Имя схемы разметки: `XMEM_MARKS`, файл `marks`, иначе умолчание."""
    return setting("XMEM_MARKS", "marks", DEFAULT_MARKS)


def hide_marks():
    """Срезать ли служебный блок с экрана. По умолчанию да.

    Умолчание именно такое, потому что блок служебный: показывать его человеку
    незачем, а забыть включить срезание легче, чем забыть выключить. Обратное
    умолчание означало бы, что каждая новая установка сперва мусорит в
    разговоре, и только потом кто-то замечает.

    Выключается на разбор поломки: `XMEM_HIDE_MARKS=0` на один запуск или
    командой `xmem marks show` насовсем.

    Слов, означающих «не срезать», несколько намеренно. Файл пишет команда
    словом (`show`), окружение ставит человек рукой и пишет привычное `0`;
    понимать надо оба, иначе рубильник срабатывает через раз в зависимости от
    того, кто его переставил.
    """
    return setting("XMEM_HIDE_MARKS", "hide-marks", "hide") not in SHOW


def as_of():
    """Момент, на который считаются сроки: `XMEM_AS_OF`, файл `as-of`, иначе пусто.

    Пусто значит «сейчас» — так ходит работа. Значение ставит замер: цифра,
    снятая на состоянии базы «как сложилось к утру прогона», не сравнима со
    вчерашней и выглядит точно так же. Настройка называет момент, а сколько
    после него живёт факт, знает режим — это разные вопросы.
    """
    return setting("XMEM_AS_OF", "as-of", "")


def memory():
    """Режим памяти: `XMEM_MEMORY`, файл `memory`, иначе умолчание.

    Отсюда факт получает срок жизни по умолчанию. Настройка называет режим, а
    не число дней — по той же причине, по какой она называет схему разметки, а
    не описывает её: число живёт рядом с кодом, который им пользуется, и не
    разъезжается с ним.
    """
    return setting("XMEM_MEMORY", "memory", DEFAULT_MEMORY)
