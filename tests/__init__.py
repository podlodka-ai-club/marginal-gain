"""Тесты. Запуск от корня: python3 -m pytest

Лента обращений уводится в сторону на весь прогон. Пишется она на каждом заходе
подсказки, в том числе из проверок, которые про ленту ничего не знают и потому
её не подменяют, — а путь по умолчанию ведёт в живую ленту пользователя. Один
прогон дописал туда четыре тысячи строк про выдуманный разговор, и счёт
«показан N раз» после этого врёт на всех записях сразу.

Подменяем через окружение и до первого импорта `domain.ledger`: пакет `tests`
грузится раньше любого модуля проверок, так что другого столь же раннего места
нет. Перекрываем жёстко, а не по умолчанию: `XMEM_LEDGER` — описанный в README
рабочий ключ, и у того, кто держит его в своём окружении, прогон ушёл бы ровно
в ту ленту, которую бережём.
"""
import os
import tempfile
from pathlib import Path

# Свой каталог на прогон, а не общее имя в /tmp: на общей машине файл с таким
# именем может принадлежать соседу, и тогда прогон падает на первой же записи.
_LEDGER = Path(tempfile.mkdtemp(prefix="xmem-tests-")) / "ledger.jsonl"
os.environ["XMEM_LEDGER"] = str(_LEDGER)
