#!/usr/bin/env python3
"""Ворота медленных проверок: собирать ли те, что поднимают живой стенд.

Стенд — это песочница, живые хуки и ожидание фоновой половины каждого хода.
Одна такая проверка стоит десятки секунд, и держать их в обычном прогоне
нельзя: батарея, которую ждут десять минут, не гоняется вовсе.

Решение вынесено сюда, а не оставлено в `conftest.py`, по одной причине:
conftest грузит pytest своим путём, и модуль, импортированный ещё и по имени,
существовал бы в двух экземплярах — со своим списком выключения в каждом.

Ключ читается в момент вызова. Прочитанный на импорте, он делает медленные
невключаемыми из уже запущенного процесса, и проверка на нём зеленеет всегда.
"""
import os

KEY = "XMEM_SLOW"

# Выключено — это отсутствие ключа и явные слова отказа. Всё остальное
# включает: человек пишет `1`, `true`, `да`, `on`, и угадывать этот список
# нельзя. Ошибка в сторону «включил» видна сразу по времени прогона, ошибка в
# сторону «не собрал» не видна вообще.
OFF = frozenset(("", "0", "false", "no", "off", "нет"))


def wanted(env=None):
    """Нужны ли медленные проверки. Читает окружение на вызове."""
    raw = (env if env is not None else os.environ).get(KEY)
    return (raw or "").strip().lower() not in OFF
